#!/usr/bin/env python3
"""Export machine-readable views of the catalog: data/edges.json and llms.txt.

Both files are generated from config.yaml and data/papers.yaml. Do not edit
them by hand; rerun this script after changing the YAML.

    python3 scripts/export.py            # write the files
    python3 scripts/export.py --check    # exit 1 if they are out of date

Edges are the union of every paper's `predecessors` and `successors` lists,
oriented "read `from` before `to`", plus the curated entries in
data/relations.yaml, which add a relation type and note to an edge (or add a
new edge). Untyped edges stay "read_before"; this exporter never guesses a type.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from scripts.catalog_io import RELATION_TYPES, load_yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_BASE_URL = "https://eribeiro.github.io/reading-tracks/"
EDGES_PATH = Path("data/edges.json")
LLMS_PATH = Path("llms.txt")
EDGE_FORMAT_VERSION = 2

NODE_FIELDS = (
    "id", "title", "year", "authors", "venue", "areas", "tags", "type",
    "difficulty", "reading_time_minutes", "lineages", "why_read",
)

_ACRONYMS = {"Ai": "AI", "Ml": "ML", "Mlops": "MLOps", "Oltp": "OLTP", "Olap": "OLAP", "Llm": "LLM"}


def human(key: str) -> str:
    """Mirror app.js's human(): kebab-case key -> display label."""
    words = key.replace("-", " ").split(" ")
    return " ".join(_ACRONYMS.get(w[:1].upper() + w[1:], w[:1].upper() + w[1:]) for w in words)


def build_graph(config: dict, papers_doc: dict, relations_doc: dict | None = None) -> dict:
    papers = papers_doc.get("papers") or []
    lineages = papers_doc.get("lineages") or {}

    nodes = []
    for p in papers:
        node = {k: p[k] for k in NODE_FIELDS if p.get(k) not in (None, [], "")}
        url = (p.get("links") or {}).get("paper")
        if url:
            node["url"] = url
        nodes.append(node)
    nodes.sort(key=lambda n: (n.get("year", 0), n["id"]))

    sources: dict[tuple[str, str], set[str]] = {}
    for p in papers:
        for pred in p.get("predecessors") or []:
            sources.setdefault((pred, p["id"]), set()).add("predecessors")
        for succ in p.get("successors") or []:
            sources.setdefault((p["id"], succ), set()).add("successors")
    edges = {
        key: {"from": key[0], "to": key[1], "relation": "read_before", "order": True, "declared_in": s}
        for key, s in sources.items()
    }
    for r in (relations_doc or {}).get("relations") or []:
        key = (r["from"], r["to"])
        edge = edges.setdefault(key, {"from": key[0], "to": key[1], "relation": "read_before",
                                      "order": r.get("order", True), "declared_in": set()})
        edge["relation"] = r["type"]
        if r.get("note"):
            edge["note"] = " ".join(str(r["note"]).split())
        edge["declared_in"].add("relations")
    edges = [{**e, "declared_in": sorted(e["declared_in"])} for _, e in sorted(edges.items())]
    relation_counts = {t: sum(e["relation"] == t for e in edges) for t in ("read_before",) + RELATION_TYPES}

    tracks = [
        {"id": key, "label": human(key), "papers": list(ids or [])}
        for key, ids in sorted(lineages.items())
    ]

    return {
        "format_version": EDGE_FORMAT_VERSION,
        "schema_version": config.get("schema_version"),
        "notes": (
            "Generated by scripts/export.py from data/papers.yaml and data/relations.yaml; "
            "do not edit by hand. Edges come from predecessors/successors and curated relations; "
            "they are conceptual reading hints, not citation claims. `order: true` means "
            "'reading `from` first helps with `to`'; `order: false` marks a tension-only link. "
            "`relation` is read_before (untyped) or a curated type: " + ", ".join(RELATION_TYPES) + ". "
            "`declared_in` records which source(s) declared the edge. "
            "Track paper lists are membership, not a prescribed reading order."
        ),
        "counts": {"papers": len(nodes), "edges": len(edges), "tracks": len(tracks),
                   "relations": relation_counts},
        "nodes": nodes,
        "edges": edges,
        "tracks": tracks,
    }


def render_edges_json(graph: dict) -> str:
    return json.dumps(graph, ensure_ascii=False, indent=2) + "\n"


def _one_line(text: str) -> str:
    return " ".join(str(text).split())


def render_llms_txt(config: dict, graph: dict, base_url: str) -> str:
    base = base_url if base_url.endswith("/") else base_url + "/"
    site = config.get("site") or {}
    by_id = {n["id"]: n for n in graph["nodes"]}
    c = graph["counts"]

    lines = [
        f"# {site.get('title', 'ReadingTracks')}",
        "",
        f"> {_one_line(site.get('tagline', ''))} A hand-curated catalog of "
        f"{c['papers']} papers grouped into {c['tracks']} reading tracks, with "
        f"{c['edges']} 'read A before B' edges.",
        "",
        "The catalog's value is its curation: which papers belong together and what to read first. "
        "Edges are conceptual reading-order hints, not a citation graph. Prefer the structured data "
        "below over scraping the HTML page.",
        "",
        "## Data",
        "",
        f"- [Graph JSON]({base}data/edges.json): papers (nodes), reading-order edges, and tracks in one file",
        f"- [Papers YAML]({base}data/papers.yaml): source of truth for papers and tracks",
        f"- [Researchers YAML]({base}data/researchers.yaml): researchers and their papers",
        f"- [Venues YAML]({base}data/venues.yaml): curated venue list",
        f"- [Site]({base}): interactive browser with filters and the Tracks view",
        "",
        "## Tracks",
        "",
    ]
    for t in graph["tracks"]:
        lines.append(f"### {t['label']}")
        lines.append("")
        members = sorted((by_id[i] for i in t["papers"] if i in by_id),
                         key=lambda n: (n.get("year", 0), n["id"]))
        for n in members:
            label = f"{_one_line(n['title'])} ({n.get('year', '?')})"
            link = f"[{label}]({n['url']})" if n.get("url") else label
            why = f": {_one_line(n['why_read'])}" if n.get("why_read") else ""
            lines.append(f"- {link}{why}")
        lines.append("")

    typed = [e for e in graph["edges"] if e["relation"] != "read_before"]
    if typed:
        lines += ["## Curated relations", "",
                  "How papers relate, in the curator's words. `contradicts` and `refines` mark "
                  "disagreements worth reading side by side.", ""]
        for e in typed:
            a, b = by_id[e["from"]], by_id[e["to"]]
            note = f": {e['note']}" if e.get("note") else ""
            verb = e["relation"].replace("_", " ")
            lines.append(f"- {_one_line(b['title'])} ({b.get('year', '?')}) {verb} "
                         f"{_one_line(a['title'])} ({a.get('year', '?')}){note}")
        lines.append("")

    lines += [
        "## Optional",
        "",
        "- [Schema reference](https://github.com/eribeiro/reading-tracks/blob/main/SCHEMA.md): field-level data format",
        "",
    ]
    return "\n".join(lines)


def build_outputs(root: Path, base_url: str) -> dict[Path, str]:
    config = load_yaml(root / "config.yaml", {})
    papers_doc = load_yaml(root / "data/papers.yaml", {})
    relations_doc = load_yaml(root / "data/relations.yaml", {})
    graph = build_graph(config, papers_doc, relations_doc)
    return {
        EDGES_PATH: render_edges_json(graph),
        LLMS_PATH: render_llms_txt(config, graph, base_url),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL, help="published site URL")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    outputs = build_outputs(args.root, args.base_url)
    stale = []
    for rel, content in outputs.items():
        path = args.root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(rel))
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")

    if stale:
        print("export.py: out of date: " + ", ".join(stale)
              + " (run python3 scripts/export.py)", file=sys.stderr)
        return 1
    if args.check:
        print("export.py: OK (generated files are up to date)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
